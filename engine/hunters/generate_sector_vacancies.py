def merge_and_update():
    cache_path = os.path.join("src", "data", "discovered_opportunities.json")
    if os.path.exists(cache_path):
        with open(cache_path, "r", encoding="utf-8") as f:
            existing = json.load(f)
    else:
        existing = []

    existing_ids = {x.get("source_identifier") for x in existing if x.get("source_identifier")}
    
    added_count = 0
    for vac in NEW_SECTOR_VACANCIES:
        if vac["source_identifier"] not in existing_ids:
            existing.insert(0, vac)
            existing_ids.add(vac["source_identifier"])
            added_count += 1

    with open(cache_path, "w", encoding="utf-8") as f:
        json.dump(existing, f, indent=2, ensure_ascii=False)

    print(f"[*] Successfully added {added_count} new sector vacancies to {cache_path}")
    print(f"[*] Total corporate vacancies in dataset: {len(existing)}")

if __name__ == "__main__":
    merge_and_update()
